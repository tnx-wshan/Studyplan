/** 기본 과목 id인지 (korean, math …) */
const BUILT_IN = new Set(["korean", "english", "math", "social", "science"]);
export const isBuiltInBase = (c: BaseCourse) => BUILT_IN.has(c.subject);

/** 학년·과목의 기본 단원. 과목은 기본 과목 id 또는 추가한 과목 이름으로 찾는다 */
export function baseCourseFor(grade: GradeId, subjectKey: string, subjectName?: string): BaseCourse | undefined {
  return BASE_COURSES.find((c) => c.grade === grade && (c.subject === subjectKey || (!!subjectName && c.subject === subjectName)));
}

/** 섹션 설명: "1학기 · 수학 1 · 중단원: 소인수분해 / 최대공약수와 최소공배수" */
export function baseSectionDescription(course: BaseCourse, section: BaseSection): string {
  const [term, , topics] = section;
  const book = term === 2 ? (course.books[1] ?? course.books[0]) : course.books[0];
  const parts = [term ? `${term}학기` : "", book, topics ? `중단원: ${topics}` : ""].filter(Boolean);
  return parts.join(" · ").slice(0, 300);
}
