/** 외전(특별 일기)인지: 업적으로 열리는 것과 레벨 20의 마지막 외전 */
export function isSideStory(entry: StoryEntry): boolean {
  return /^[nc]s/.test(entry.id);
}

export function storyFor(style: "cute" | "noir"): StoryEntry[] {
  return style === "noir" ? NOIR_STORY : CUTE_STORY;
}

export function isUnlocked(entry: StoryEntry, level: number, badges: Set<string>): boolean {
  return "level" in entry.unlock ? level >= entry.unlock.level : badges.has(entry.unlock.badge);
}

/** 두 테마의 같은 순번 기록은 같은 '읽음' 상태를 쓴다 (n3 ↔ c3) */
export function storyKey(id: string): string {
  return id.slice(1);
}

export function renderStory(entry: StoryEntry, name: string, species: PetSpecies): string[] {
  const extra = entry.bySpecies?.[species];
  return [...entry.body, ...(extra ? [extra] : [])].map((p) => p.replaceAll("{name:이라}", withIRa(name)).replaceAll("{name}", name));
}

/** 열렸지만 아직 읽지 않은 기록 수 */
export function unreadCount(style: "cute" | "noir", level: number, badges: Set<string>, read: string[]): number {
  const seen = new Set(read);
  return storyFor(style).filter((e) => isUnlocked(e, level, badges) && !seen.has(storyKey(e.id))).length;
}
